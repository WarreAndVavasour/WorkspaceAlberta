def _public_origin_base() -> str:
    return (
        os.environ.get("WA_PUBLIC_ORIGIN", "").strip().rstrip("/")
        or "https://elbowsupknivesout.warreandvavasour.com"
    )


def checkout_url(
    plan: str = "pro",
    *,
    email: str = "",
    user_id: str = "",
) -> str:
    """Build a direct checkout link bound to the caller's identity when known."""
    params: dict[str, str] = {"plan": plan}
    if email:
        params["email"] = email.strip().lower()
    if user_id:
        params["user_id"] = user_id.strip()
    return f"{_public_origin_base()}/checkout?{urlencode(params)}"


def prefilled_subscribe_url(*, email: str = "", user_id: str = "", base_url: str = "") -> str:
    """Append Stripe Payment Link prefill parameters when identity is known."""
    target = (base_url or SUBSCRIBE_URL).strip()
    params: dict[str, str] = {}
    if email:
        params["prefilled_email"] = email.strip().lower()
    if user_id:
        params["client_reference_id"] = user_id.strip()
    if not params:
        return target
    sep = "&" if "?" in target else "?"
    return f"{target}{sep}{urlencode(params)}"


def access_help(
    status_code: int,
    tool_name: str = "",
    *,
    email: str = "",
    user_id: str = "",
) -> dict[str, Any]:
    """What a client or person must do after a denied call, as plain steps.

    Sent in the HTTP 401 body and in MCP tool errors, so an agent can tell the
    person how to get access instead of guessing (or asking for unrelated keys).
    """
    is_pro = tool_name in PRO_TOOLS
    pro_checkout = checkout_url("pro", email=email, user_id=user_id) if (email or user_id) else SUBSCRIBE_URL
    pack_1_checkout = checkout_url("pack_1", email=email, user_id=user_id)
    pack_3_checkout = checkout_url("pack_3", email=email, user_id=user_id)
    portal_url = f"{_public_origin_base()}/billing/portal"
    if status_code == 402:
        steps = [
            f"Subscribe to workspaceAlberta Pro (C$85/month, unlimited): {pro_checkout}",
            f"Or buy a pay-per-tender Bid Pack (no subscription): C$19 for 1 tender ({pack_1_checkout}) or C$49 for 3 tenders ({pack_3_checkout}).",
            "Use the same email for checkout and sign-in, then call the tool again — your client keeps the same sign-in.",
        ]
    else:
        steps = [
            "Sign in when your client asks (OAuth). In Claude, choose Connect on the workspaceAlberta connector.",
            "If your client cannot sign in and you have a legacy subscriber key, send `Authorization: Bearer wa_live_...`.",
        ]
        if is_pro:
            steps.append(
                f"Signing in is free and includes {FREE_PRO_CREDITS} free tender review credits. "
                f"After your free runs, upgrade to Pro (C$85/mo) or a C$19 Bid Pack: {SUBSCRIBE_URL}"
            )
        else:
            steps.append(
                "Signing in is free and never starts a paid subscription. "
                f"Includes saved profiles, bid/no-bid scorecards, a {FREE_WATCHLIST_LIMIT}-tender watchlist, and {FREE_PRO_CREDITS} free tender reviews."
            )
    return {
        "tool": tool_name or None,
        "requires": "pro" if is_pro else "sign_in",
        "steps": steps,
        "subscribe_url": SUBSCRIBE_URL,
        "checkout_url": pro_checkout,
        "bid_pack_urls": {"pack_1": pack_1_checkout, "pack_3": pack_3_checkout},
        "billing_portal_url": portal_url,
        "pricing_url": PRICING_URL,
        "support_url": SUPPORT_URL,
        "third_party_keys": NO_THIRD_PARTY_KEYS,
    }


def access_help_text(
    status_code: int,
    tool_name: str = "",
    *,
    email: str = "",
    user_id: str = "",
) -> str:
    """The same help as numbered Markdown steps for a tool error."""
    help_ = access_help(status_code, tool_name, email=email, user_id=user_id)
    lines = [f"{index}. {step}" for index, step in enumerate(help_["steps"], 1)]
    lines.append("")
    lines.append(help_["third_party_keys"])
    lines.append(
        f"Pricing: {help_['pricing_url']} · Manage billing: {help_['billing_portal_url']} · Help: {help_['support_url']}"
    )
    return "\n".join(lines)


_cache: dict[str, tuple[float, dict[str, Any] | None]] = {}


class GateError(Exception):
    """Raised when a Pro tool is called without a valid subscription key.

    ``status_code`` maps cleanly onto HTTP: 401 (missing/invalid key),
    402 (key known but subscription not active), 503 (no validator
    configured).
    """

    def __init__(
        self,
        status_code: int,
        message: str,
        *,
        email: str = "",
        user_id: str = "",
    ) -> None:
        self.status_code = status_code
        self.email = email
        self.user_id = user_id
        super().__init__(message)


# ============== Key material ==============


def generate_api_key() -> str:
    """Return a new subscriber key. Shown once; only its hash is stored."""
    return KEY_PREFIX + secrets.token_urlsafe(32)


def hash_api_key(key: str) -> str:
    """SHA-256 hex digest of a key — the only form ever persisted."""
    return hashlib.sha256(key.strip().encode("utf-8")).hexdigest()


def extract_bearer_key(authorization_header: str | None) -> str:
    """Pull the key out of an ``Authorization: Bearer ...`` header value."""
    if not authorization_header:
        return ""
    parts = authorization_header.strip().split(None, 1)
    if len(parts) == 2 and parts[0].lower() == "bearer":
        return parts[1].strip()
    return ""


# ============== Configuration ==============


def supabase_config() -> tuple[str, str]:
    url = os.environ.get("SUPABASE_URL", "").strip().rstrip("/")
    key = (
        os.environ.get("SUPABASE_SERVICE_ROLE_KEY", "").strip()
        or os.environ.get("SUPABASE_SECRET_KEY", "").strip()
    )
    return url, key

def stripe_secret_key() -> str:
    return os.environ.get("STRIPE_SECRET_KEY", "").strip()


def gate_enabled() -> bool:
    """The gate is active unless explicitly disabled or nothing can validate."""
    if os.environ.get("WA_GATE_DISABLED", "").lower() in {"1", "true", "yes"}:
        return False
    url, key = supabase_config()
    return bool(url and key) or bool(stripe_secret_key())


# ============== Validators ==============


def _supabase_lookup(key_hash: str) -> dict[str, Any] | None:
    """Fetch the subscriber row for a key hash, or None."""
    url, service_key = supabase_config()
    params = urlencode(
        {
            "key_hash": f"eq.{key_hash}",
            "select": "key_hash,stripe_customer_id,email,status,plan",
            "limit": "1",
        }
    )
    request = Request(
        f"{url}/rest/v1/wa_subscribers?{params}",
        headers={
            "apikey": service_key,
            "Authorization": f"Bearer {service_key}",
            "Accept": "application/json",
        },
    )
    try:
        with urlopen(request, timeout=15) as response:
            rows = json.loads(response.read().decode("utf-8"))
    except (HTTPError, URLError, json.JSONDecodeError) as exc:
        raise GateError(503, f"Subscriber lookup failed: {exc}") from exc
    return rows[0] if rows else None


def _stripe_lookup(key_hash: str) -> dict[str, Any] | None:
    """Fallback: find a Stripe customer by metadata wa_key_hash and check subs."""
    secret = stripe_secret_key()
    query = quote(f"metadata['wa_key_hash']:'{key_hash}'")
    request = Request(
        f"https://api.stripe.com/v1/customers/search?query={query}&limit=1",
        headers={"Authorization": f"Bearer {secret}"},
    )
    try:
        with urlopen(request, timeout=15) as response:
            body = json.loads(response.read().decode("utf-8"))
    except (HTTPError, URLError, json.JSONDecodeError) as exc:
        raise GateError(503, f"Stripe lookup failed: {exc}") from exc

    customers = body.get("data", [])
    if not customers:
        return None
    customer = customers[0]

    sub_request = Request(
        f"https://api.stripe.com/v1/subscriptions?customer={customer['id']}&status=active&limit=1",
        headers={"Authorization": f"Bearer {secret}"},
    )
    try:
        with urlopen(sub_request, timeout=15) as response:
            subs = json.loads(response.read().decode("utf-8"))
    except (HTTPError, URLError, json.JSONDecodeError) as exc:
        raise GateError(503, f"Stripe subscription check failed: {exc}") from exc

    active = bool(subs.get("data"))
    return {
        "key_hash": key_hash,
        "stripe_customer_id": customer["id"],
        "email": customer.get("email", ""),
        "status": "active" if active else "cancelled",
        "plan": "pro",
    }


def validate_key(key: str) -> dict[str, Any]:
    """Validate a raw API key, returning the subscriber record.

    Raises :class:`GateError` (401 unknown key, 402 inactive subscription,
    503 validator unavailable). Results — including "unknown" — are cached
    for ``CACHE_TTL_SECONDS``.
    """
    if not key or not key.startswith(KEY_PREFIX):
        raise GateError(401, "A WorkspaceAlberta Pro API key is required for this tool.")

    key_hash = hash_api_key(key)
    now = time.time()
    cached = _cache.get(key_hash)
    if cached and now - cached[0] < CACHE_TTL_SECONDS:
        record = cached[1]
    else:
        url, service_key = supabase_config()
        if url and service_key:
            record = _supabase_lookup(key_hash)
        elif stripe_secret_key():
            record = _stripe_lookup(key_hash)
        else:
            raise GateError(503, "Subscription validation is not configured on this server.")
        _cache_put(key_hash, record, now)

    if record is None:
        raise GateError(401, "Unknown API key. Check the key from your subscription email.")
    if record.get("status") != "active":
        raise GateError(
            402,
            "Your subscription is not active. Manage billing via Stripe or resubscribe at subscribe.html.",
        )
    return record


def check_tool_access(tool_name: str, authorization_header: str | None) -> dict[str, Any] | None:
    """Gate one tool call. Returns the subscriber record when authenticated.

    Rules:

    - Gate disabled (dev / no validator configured): always anonymous.
    - A valid key is honoured on *any* tool, so a subscriber's profile and
      watchlist are tenant-scoped even on free tools.
    - Pro tools without a valid key raise :class:`GateError`.
    - Free tools with a bad key degrade to anonymous rather than failing.
    """
    if not gate_enabled():
        return None

    key = extract_bearer_key(authorization_header)
    is_pro = tool_name in PRO_TOOLS

    if not key:
        if is_pro:
            raise GateError(401, "A WorkspaceAlberta Pro API key is required for this tool.")
        return None

    try:
        return validate_key(key)
    except GateError:
        if is_pro:
            raise
        return None


def _cache_put(key_hash: str, record: dict[str, Any] | None, now: float) -> None:
    """Insert a validation result, keeping the cache bounded."""
    if len(_cache) >= MAX_CACHE_ENTRIES:
        expired = [k for k, (ts, _) in _cache.items() if now - ts >= CACHE_TTL_SECONDS]
        for stale in expired:
            _cache.pop(stale, None)
        if len(_cache) >= MAX_CACHE_ENTRIES:
            # Still full of fresh entries (e.g. a key-guessing flood): drop
            # the oldest half rather than refusing to cache real subscribers.
            for stale in sorted(_cache, key=lambda k: _cache[k][0])[: MAX_CACHE_ENTRIES // 2]:
                _cache.pop(stale, None)
    _cache[key_hash] = (now, record)


def clear_cache() -> None:
    """Drop all cached validations (used by tests and the webhook)."""
    _cache.clear()
